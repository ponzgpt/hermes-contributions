// Rewrites upstream.json from what Nous publishes right now.
//
// Everything this repo quotes about Hermes Agent — the version, the installer,
// the model prices — lives in upstream.json and nowhere else. Pages are built
// from it; scripts/freshness.mjs fails when it no longer matches upstream.
// Run this when freshness.mjs complains, then read the diff before committing:
// a price moving is news, and the guide's prose may need to move with it.
//
//   node scripts/refresh-upstream.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { SOURCES, PROFILES, perMillion, findModel } from './upstream-lib.mjs'

const get = async (url, as = 'text') => {
  const r = await fetch(url, { headers: { 'user-agent': 'hermes-contributions/freshness' } })
  if (!r.ok) throw new Error(`${url} → HTTP ${r.status}`)
  return as === 'json' ? r.json() : r.text()
}

const release = await get(SOURCES.release, 'json')
const installer = await get(SOURCES.installer)
const mirror = await get(SOURCES.installerMirror)
const catalogue = (await get(SOURCES.models, 'json')).data

// The release is named "Hermes Agent v0.21.3 (v2026.9.14)": a product version
// inside a dated tag. Pages quote the product version; the tag dates it.
const version = (release.name.match(/v\d+\.\d+\.\d+/) || [null])[0]
if (!version) throw new Error(`cannot read a version out of release name: ${release.name}`)

const sha256 = (s) => createHash('sha256').update(s).digest('hex')
const previous = JSON.parse(readFileSync(new URL('../upstream.json', import.meta.url), 'utf8'))

const next = {
  _: 'Generated by scripts/refresh-upstream.mjs. Checked by scripts/freshness.mjs. Do not hand-edit prices.',
  checked: new Date().toISOString().slice(0, 10),
  release: { version, tag: release.tag_name, published: release.published_at.slice(0, 10) },
  installer: {
    url: SOURCES.installer,
    mirror: SOURCES.installerMirror,
    sha256: sha256(installer),
    matches_mirror: sha256(installer) === sha256(mirror),
    sh: `curl -fsSL ${SOURCES.installer} | bash`,
    ps1: 'iex (irm https://hermes-agent.nousresearch.com/install.ps1)',
  },
  catalogue_size: catalogue.length,
  profiles: PROFILES.map((p) => ({
    ...p,
    main: priced(p.main),
    aux: priced(p.aux),
  })),
}

function priced(id) {
  const m = findModel(catalogue, id)
  if (!m) throw new Error(`model no longer in the catalogue: ${id}`)
  const [input, output] = perMillion(m)
  return { id, name: m.name, input, output, context: m.context_length }
}

writeFileSync(new URL('../upstream.json', import.meta.url), JSON.stringify(next, null, 2) + '\n')

const was = JSON.stringify(previous.profiles) !== JSON.stringify(next.profiles)
console.log(
  `upstream.json ← ${next.release.version} (${next.release.tag}), ${catalogue.length} models`
)
console.log(was ? 'prices moved — read the diff before committing' : 'prices unchanged')
